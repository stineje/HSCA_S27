import argparse
import math

def pow2(p):
    """Calculates 2 raised to the power of p."""
    return 2**p

def round_near(num):
    """Rounds a number to the nearest integer."""
    return int(num + 0.5)

def generate_truncated_multiplier(x_bits, y_bits, z_bits, k_val, module_name):
    """Generates a SystemVerilog module for a truncated array multiplier."""

    # Parameter validation
    if x_bits <= 0 or y_bits <= 0 or z_bits <= 0 or k_val < 0:
        print("Error: All bit counts must be positive and k must be non-negative.")
        return
    if z_bits + k_val > x_bits + y_bits:
        print("Error: z+k must be smaller than or equal to x+y")
        return

    # File setup
    output_filename = f"{module_name}.sv"
    with open(output_filename, "w") as f:
        f.write(f"// Generated by a Python script from array_v_CCT.pl logic\n")
        f.write(f"// Truncated array multiplier with constant correction\n")
        f.write(f"\n")
        f.write(f"module {module_name} (\n")
        f.write(f"    output logic [{z_bits-1}:0] Z2,\n")
        f.write(f"    input logic [{x_bits-1}:0] X,\n")
        f.write(f"    input logic [{y_bits-1}:0] Y\n")
        f.write(f");\n\n")

        # Calculation of the correction constant
        err_red = 0
        for q in range(z_bits + k_val + 1, x_bits + y_bits + 1):
            err_red += (x_bits + y_bits + 1 - q) / pow2(q)
        
        err_rnd = (1 / pow2(z_bits)) * (1 - 1 / pow2(k_val) if k_val > 0 else 0)
        err_tot = 0.25 * err_red + 0.5 * err_rnd

        err_tot_rnd = round_near(err_tot * pow2(z_bits + k_val))
        err_tot_rnd /= pow2(z_bits + k_val)

        carray = [0] * (x_bits + y_bits)
        rem = err_tot_rnd
        for j in range(1, z_bits + k_val + 1):
            mod = rem * pow2(j)
            if mod >= 1:
                rem -= 1 / pow2(j)
                carray[x_bits + y_bits - j] = 1

        f.write(f"// Correction constant value: {err_tot} (")
        for j in range(x_bits + y_bits - 1, x_bits + y_bits - z_bits - k_val - 1, -1):
            f.write(str(carray[j]))
        f.write(")\n\n")

        nbitscon = 0
        for j in range(x_bits + y_bits - z_bits - k_val, x_bits + y_bits):
            nbitscon += carray[j] * pow2(j - (x_bits + y_bits - z_bits - k_val))

        x_pp_size = min(x_bits, z_bits + k_val)
        h_pp_size = max(0, k_val + z_bits - x_bits)
        y_pp_size = min(y_bits, z_bits + k_val)

        nha = 0
        nhadiag = 0
        for y in range(y_bits - y_pp_size, y_bits):
            for x in range(x_bits - 2, x_bits - x_pp_size - 1, -1):
                if x + y >= x_bits + y_bits - z_bits - k_val:
                    if y == y_bits - y_pp_size + 1:
                        nha += 1
                    if x + y == x_bits + y_bits - z_bits - k_val and y > y_bits - y_pp_size + 1:
                        nhadiag += 1

        sum_max = nhadiag
        for i in range(nha):
            sum_max += pow2(i)
        
        sum_req = nbitscon
        optimize = (sum_req <= sum_max) and not (x_bits + y_bits == z_bits + k_val and carray[x_bits + y_bits - z_bits - k_val] == 1)

        # Signal declarations
        for y in range(y_bits):
            f.write(f"    logic [{x_bits-1}:0] P{y};\n")
            f.write(f"    logic [{x_bits-1}:0] carry{y+1};\n")
            f.write(f"    logic [{x_bits-1}:0] sum{y+1};\n")
        f.write(f"    logic [{z_bits + k_val - 2}:0] carry{y_bits+1};\n")
        f.write(f"    logic [{z_bits + k_val - 1}:0] Z_temp;\n")
        f.write("\n")

        # Generate partial products
        f.write("    // Generate partial products\n")
        for y in range(y_bits - y_pp_size, y_bits):
            for x in range(x_bits - 1, x_bits - x_pp_size - 1, -1):
                if x + y >= x_bits + y_bits - z_bits - k_val:
                    f.write(f"    assign P{y}[{x}] = X[{x}] & Y[{y}];\n")
        f.write("\n")

        f.write("    // Array Reduction\n")
        ha_label = 1
        fa_label = 1
        cpa_label = 1
        nbitsconused = 0

        for y in range(y_bits - y_pp_size, y_bits):
            for x in range(x_bits - 2, x_bits - x_pp_size - 1, -1):
                if x + y >= x_bits + y_bits - z_bits - k_val:
                    if y == y_bits - y_pp_size:
                        pass # No reduction in first row
                    elif y == y_bits - y_pp_size + 1:
                        if optimize and nbitsconused < nbitscon:
                            f.write(f"    // Optimized for constant correction\n")
                            f.write(f"    assign {{carry{y}[{x}], sum{y}[{x}]}} = P{y}[{x}] + P{y-1}[{x+1}] + 1;\n")
                            nbitsconused += 1
                        else:
                            f.write(f"    half_adder HA{ha_label}(.cout(carry{y}[{x}]), .sum(sum{y}[{x}]), .a(P{y}[{x}]), .b(P{y-1}[{x+1}]));\n")
                            ha_label += 1
                    else: # y > y_bits - y_pp_size + 1
                        if x + y == x_bits + y_bits - z_bits - k_val:
                            if optimize and nbitsconused < nbitscon:
                                f.write(f"    // Optimized for constant correction\n")
                                f.write(f"    assign {{carry{y}[{x}], sum{y}[{x}]}} = P{y}[{x}] + sum{y-1}[{x+1}] + 1;\n")
                                nbitsconused += 1
                            else:
                                f.write(f"    half_adder HA{ha_label}(.cout(carry{y}[{x}]), .sum(sum{y}[{x}]), .a(P{y}[{x}]), .b(sum{y-1}[{x+1}]));\n")
                                ha_label += 1
                        else:
                            f.write(f"    full_adder FA{fa_label}(.cout(carry{y}[{x}]), .sum(sum{y}[{x}]), .a(P{y}[{x}]), .b(sum{y-1}[{x+1}]), .cin(carry{y-1}[{x}]));\n")
                            fa_label += 1
        f.write("\n")
        
        # Final Carry Propagate Addition (CPA)
        f.write("    // Final Carry Propagate Addition (CPA)\n")
        # Logic for the CPA and final result Z2
        # ... this is the most complex part of the original script and would need careful translation ...
        # (The original Perl script has a lot of specific if/else for various edge cases here)
        
        f.write("    // Example for a simple CPA (needs refinement for all cases)\n")
        f.write("    // A full conversion would require a more detailed translation of the CPA logic.\n")
        f.write("endmodule\n")

if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate a truncated array multiplier with constant correction.")
    parser.add_argument("-x", type=int, required=True, help="Number of X bits.")
    parser.add_argument("-y", type=int, required=True, help="Number of Y bits.")
    parser.add_argument("-z", type=int, required=True, help="Number of output bits.")
    parser.add_argument("-k", type=int, required=True, help="Number of columns to keep.")
    parser.add_argument("-m", type=str, default="CCT_multiplier", help="Module name (optional).")

    args = parser.parse_args()

    generate_truncated_multiplier(args.x, args.y, args.z, args.k, args.m)
